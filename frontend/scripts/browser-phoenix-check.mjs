import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
const meta=JSON.parse(fs.readFileSync(process.argv[2],'utf8')),output=path.resolve(process.argv[3]),base=process.argv[4]||'http://127.0.0.1:3012';
fs.mkdirSync(output,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const ctx=await browser.newContext({viewport:{width:1580,height:910}});
await ctx.addInitScript(()=>{sessionStorage.setItem('phoenix.workbench.token','phoenix-local-browser-fixture-token-2026');localStorage.setItem('phoenix.themePreference','light');localStorage.setItem('phoenix.motion','reduce');});
const page=await ctx.newPage(),errors=[],failed=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.url().startsWith(base)&&r.status()>=400)failed.push({path:new URL(r.url()).pathname,status:r.status()});});
const shot=name=>page.screenshot({path:path.join(output,name),fullPage:false});
try{
 await page.goto(base);
 await expect(page.getByRole('heading',{name:'开始解题',exact:true})).toBeVisible({timeout:20000});
 await expect(page.getByLabel('描述一道题')).toBeVisible();
 await expect(page.locator('.suggest-card')).toHaveCount(3);
 expect(await page.locator('.px-draft-advanced').count()).toBe(0);
 await shot('Phoenix-01-phoenix-new-challenge.png');checks.push('original Phoenix welcome, templates and central composer');
 await page.locator('.suggest-card').first().click();
 expect(await page.getByLabel('描述一道题').inputValue()).not.toBe('');
 await page.getByRole('button',{name:'高级',exact:false}).click();
 await expect(page.locator('#draft-advanced')).toBeVisible();
 await page.getByRole('button',{name:'高级',exact:false}).click();checks.push('template fills native draft; advanced options expand');
 await page.goto(`${base}/run/${meta.paused_run_id}`);
 await expect(page.getByRole('button',{name:'事实: 0',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'事实: 0',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'事实',exact:true})).toContainText('当前没有相关内容');
 await expect(page.getByRole('tab',{name:'对话',exact:true})).toHaveAttribute('aria-selected','true');
 await shot('Phoenix-02-phoenix-fact-popover.png');
 await page.keyboard.press('Escape');checks.push('original Phoenix Fact popover stays in conversation, empty state matches');
 await page.goto(`${base}/run/${meta.demo_run_id}`);
 await expect(page.getByRole('button',{name:'事实: 2',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'事实: 2',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'事实',exact:true})).toContainText('待独立验证');
 await page.keyboard.press('Escape');checks.push('native cited observations remain unverified in the original popover');
 await page.getByRole('tab',{name:'运行时',exact:true}).click();
 await expect(page.locator('.rt-console')).toBeVisible();
 await expect(page.locator('.rt-graph')).toBeVisible();
 await expect(page.locator('.rt-ledger-pane')).toBeVisible();
 expect((await page.locator('.rt-console').boundingBox()).width).toBeGreaterThan(1500);
 expect(await page.getByRole('complementary',{name:'运行信息'}).count()).toBe(0);
 await expect(page.locator('.rt-console')).toContainText('解题智能体甲');
 await expect(page.locator('.rt-console')).toContainText('未完整计价');
 await shot('Phoenix-03-phoenix-runtime-waterfall.png');checks.push('original full-width Phoenix waterfall, worker bars, native costs and event ledger');
 await page.getByRole('button',{name:/收起图谱/}).click();
 await expect(page.getByRole('button',{name:/展开图谱/})).toBeVisible();
 await page.getByRole('button',{name:/展开图谱/}).click();
 await page.getByPlaceholder('搜索执行单元、命令或事件').fill('读取文件');
 await expect(page.locator('.rt-console')).toContainText('读取文件');
 await page.getByPlaceholder('搜索执行单元、命令或事件').fill('');checks.push('native waterfall search and original collapse controls work');
 await page.getByRole('button',{name:'用量',exact:true}).click();
 await expect(page.locator('.px-usage-table')).toContainText('planner');checks.push('runtime usage is backed by persisted model calls');
 await page.getByRole('tab',{name:'协作图',exact:true}).click();
 await expect(page.locator('.react-flow__node').first()).toBeVisible();await shot('Phoenix-17-collaboration-graph.png');checks.push('original collaboration graph remains wired');
 await page.getByRole('tab',{name:'对话',exact:true}).click();
 await page.locator('.px-thread-scroll').evaluate(el=>el.scrollTop=0);
 await shot('Phoenix-04-phoenix-conversation.png');
 await page.setViewportSize({width:390,height:844});
 await page.goto(base);
 await expect(page.getByLabel('描述一道题')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await shot('Phoenix-05-phoenix-mobile.png');checks.push('central composer remains usable on narrow screens');
 expect(errors).toEqual([]);expect(failed).toEqual([]);
 fs.writeFileSync(path.join(output,'browser-results.json'),JSON.stringify({checks,errors,failed},null,2));
 console.log(JSON.stringify({passed:checks.length,errors,failed},null,2));
}finally{await browser.close();}
